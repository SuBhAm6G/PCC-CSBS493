--------------------------------------------------------------------------------
-- Import IEEE library
--------------------------------------------------------------------------------
LIBRARY ieee;

--------------------------------------------------------------------------------
-- Import std_logic and std_logic_vector definitions
--------------------------------------------------------------------------------
USE ieee.std_logic_1164.ALL;

--------------------------------------------------------------------------------
-- Testbench Entity
-- No ports required because test signals are generated internally
--------------------------------------------------------------------------------
ENTITY piso_test IS
END piso_test;

--------------------------------------------------------------------------------
-- Testbench Architecture
--------------------------------------------------------------------------------
ARCHITECTURE behavior OF piso_test IS

    ----------------------------------------------------------------------------
    -- Component Declaration
    -- Unit Under Test (UUT)
    ----------------------------------------------------------------------------
    COMPONENT piso
    PORT(
         clk : IN  std_logic;
         reset : IN  std_logic;
         load : IN  std_logic;
         pin : IN  std_logic_vector(3 downto 0);
         sout : OUT  std_logic
        );
    END COMPONENT;

    ----------------------------------------------------------------------------
    -- Input Signals
    ----------------------------------------------------------------------------
    signal clk : std_logic := '0';

    signal reset : std_logic := '0';

    signal load : std_logic := '0';

    signal pin : std_logic_vector(3 downto 0)
                 := (others => '0');

    ----------------------------------------------------------------------------
    -- Output Signal
    ----------------------------------------------------------------------------
    signal sout : std_logic;

    ----------------------------------------------------------------------------
    -- Clock Period
    ----------------------------------------------------------------------------
    constant clk_period : time := 10 ns;

BEGIN

    ----------------------------------------------------------------------------
    -- UUT = Unit Under Test
    ----------------------------------------------------------------------------
    uut: piso PORT MAP (

          clk => clk,

          reset => reset,

          load => load,

          pin => pin,

          sout => sout

        );

    ----------------------------------------------------------------------------
    -- Clock Generation Process
    -- Generates a continuous square wave
    ----------------------------------------------------------------------------
    clk_process :process
    begin

        clk <= '0';
        wait for clk_period/2;

        clk <= '1';
        wait for clk_period/2;

    end process;

    ----------------------------------------------------------------------------
    -- Stimulus Process
    ----------------------------------------------------------------------------
    stim_proc: process
    begin

        ------------------------------------------------------------------------
        -- Apply Reset
        -- Clears all flip-flops
        ------------------------------------------------------------------------
        reset <= '1';

        wait for 20 ns;

        ------------------------------------------------------------------------
        -- Release Reset
        ------------------------------------------------------------------------
        reset <= '0';

        ------------------------------------------------------------------------
        -- Enable Parallel Load
        ------------------------------------------------------------------------
        load <= '1';

        ------------------------------------------------------------------------
        -- Load 4-bit parallel value
        ------------------------------------------------------------------------
        pin <= "1011";

        ------------------------------------------------------------------------
        -- Wait one clock cycle so loading can occur
        ------------------------------------------------------------------------
        wait for clk_period;

        ------------------------------------------------------------------------
        -- Disable Load
        -- Register now enters shift mode
        ------------------------------------------------------------------------
        load <= '0';

        ------------------------------------------------------------------------
        -- Shift Clock 1
        ------------------------------------------------------------------------
        wait for clk_period;

        ------------------------------------------------------------------------
        -- Shift Clock 2
        ------------------------------------------------------------------------
        wait for clk_period;

        ------------------------------------------------------------------------
        -- Shift Clock 3
        ------------------------------------------------------------------------
        wait for clk_period;

        ------------------------------------------------------------------------
        -- Shift Clock 4
        ------------------------------------------------------------------------
        wait for clk_period;

        ------------------------------------------------------------------------
        -- Stop simulation
        ------------------------------------------------------------------------
        wait;

    end process;

END;